"""Label every file in results/: what it is, which model/arm/seed, which GPU produced it, and its headline number.

Files are never renamed (the check-in scripts and tests read them by name); this writes an index next to them instead.

    python explore/results_index.py results          -> results/index.json + results/INDEX.md

Hardware comes from each file's recorded versions; files from before versions were recorded are listed in LEGACY.
Runs repeated on other hardware must carry a hardware suffix so they never overwrite an existing file, e.g.
train-pilot_qwen3-1.7b_rae_s0-rtx5080.json and eval-pilot_qwen3-1.7b_rae_s0-step30-rtx5080.json (see HW_SUFFIX).
"""

import argparse
import json
import re
from pathlib import Path

# Training files written before versions.json existed (Check-in 3, Colab T4; see docs/README.md)
LEGACY = {
    "train-pilot_qwen3-1.7b_rae_s0.json": {"gpu": "Tesla T4"},
    "train-pilot_qwen3-1.7b_shared_s0.json": {"gpu": "Tesla T4", "note": "partial: stopped at step 20 of 30"},
}
HW_SUFFIX = {"hpc": "NVIDIA H100 PCIe", "rtx5080": "NVIDIA GeForce RTX 5080", "t4": "Tesla T4"}
SOURCE = {"Tesla T4": "Colab T4 (Check-ins 2-3)", "NVIDIA H100 PCIe": "SJSU HPC H100 (Check-in 5)",
          "NVIDIA GeForce RTX 5080": "Teammate RTX 5080 (Check-in 4)"}
SUPPORT = {  # non-run files: what they hold
    "benchmark_stats.json": "Benchmark sizes and minimum detectable effects (Check-in 1)",
    "checkin2_stats.json": "Base 1.7B vs 4B paired MATH-500 statistics (Check-in 2)",
    "checkin3_stats.json": "Pilot training and transfer summary (Check-in 3)",
    "kuhn_spiral.json": "Scripted-policy matchups, SPIRAL's KuhnPoker-v1 (Check-in 1)",
    "kuhn_textarena.json": "Scripted-policy matchups, TextArena 0.7.4 KuhnPoker (Check-in 1)",
    "kuhn_textarena_fixed.json": "Scripted-policy matchups, corrected stakes control (Check-in 1)",
    "seed_stats.json": "Per-arm effects pooled over seeds (explore/seed_stats.py)",
}
COLLAPSE_TOKENS = 50  # final reply length (tokens/turn) below which a run is flagged as length-collapsed


def _gpu(name: str, data: dict) -> str | None:
    gpu = (data.get("versions") or {}).get("gpu") or LEGACY.get(name, {}).get("gpu")
    if gpu:
        return gpu
    m = re.search(r"-(" + "|".join(HW_SUFFIX) + r")(?:-|\.json)", name)
    return HW_SUFFIX[m.group(1)] if m else None


def _arm(run_id: str) -> str:
    return "self-play" if run_id.startswith("selfplay") else "pilot vs never_fold" if run_id.startswith("pilot") else ""


def describe(path: Path) -> dict:
    name, data = path.name, json.loads(path.read_text(encoding="utf-8"))
    entry = {"file": name, "kind": "support", "description": SUPPORT.get(name, "")}
    if name.startswith("train-"):
        rows, cfg = data["metrics"], data["config"]
        tokens = rows[-1]["completion_tokens_per_turn"]
        entry.update(kind="train", run_id=data["run_id"], model=cfg.get("model"), arm=_arm(data["run_id"]),
                     estimator=cfg.get("estimator"), seed=cfg.get("seed"), steps=rows[-1]["step"],
                     planned_steps=cfg.get("steps"), description=data.get("label", ""),
                     final_tokens_per_turn=round(tokens, 1),
                     note="; ".join(filter(None, [LEGACY.get(name, {}).get("note"),
                                                  "reply-length collapse" if tokens < COLLAPSE_TOKENS else ""])))
    elif name.startswith("eval-"):
        rows = data["results"]
        acc = {r["benchmark"]: r["value"] for r in rows if r["metric"] == "accuracy"}
        first = rows[0]
        base = first.get("estimator") in (None, "", "none") and "base" in data["run_id"]
        entry.update(kind="eval", run_id=data["run_id"], model=first.get("model"),
                     arm="base model" if base else _arm(re.sub(r"^eval-", "", data["run_id"])),
                     estimator=None if base else first.get("estimator"), seed=None if base else first.get("seed"),
                     step=first.get("step"), benchmarks=sorted(acc), accuracy={k: round(v, 4) for k, v in acc.items()})
    elif name.startswith("kuhn-"):
        entry.update(kind="kuhn", run_id=data["run_id"], description="Base model playing Kuhn Poker vs never_fold")
    entry["gpu"] = _gpu(name, data)
    entry["source"] = SOURCE.get(entry["gpu"], "")
    return entry


def to_markdown(entries: list[dict]) -> str:
    def row(cells):
        return "| " + " | ".join("" if c is None else str(c) for c in cells) + " |"

    out = ["# results/ index", "",
           "Generated by `python explore/results_index.py results`; do not edit by hand. Files are never renamed or",
           "deleted. Comparisons are only made within one GPU type (H100 runs against the H100 base, T4 against T4).",
           "Runs repeated on other hardware get a hardware suffix, e.g. `train-<run_id>-rtx5080.json`,",
           "`eval-<run_id>-step30-rtx5080.json`, so they never overwrite an existing file.", ""]
    for source in sorted({e["source"] for e in entries if e["kind"] != "support"}):
        group = [e for e in entries if e["source"] == source and e["kind"] != "support"]
        out += [f"## {source or 'unknown hardware'}", "", "### Training runs", "",
                row(["File", "Arm", "Estimator", "Seed", "Steps", "Final tokens/turn", "Note"]),
                row(["---"] * 7)]
        out += [row([f"`{e['file']}`", e["arm"], e["estimator"], e["seed"], f"{e['steps']}/{e['planned_steps']}",
                     e["final_tokens_per_turn"], e["note"]]) for e in group if e["kind"] == "train"]
        out += ["", "### Evaluations", "", row(["File", "Model", "Arm", "Estimator", "Seed", "Accuracy"]),
                row(["---"] * 6)]
        out += [row([f"`{e['file']}`", e["model"], e["arm"], e["estimator"], e["seed"],
                     ", ".join(f"{k} {100 * v:.1f}%" for k, v in e["accuracy"].items())])
                for e in group if e["kind"] == "eval"]
        out += [row([f"`{e['file']}`", "", e["description"], "", "", ""]) for e in group if e["kind"] == "kuhn"]
        out.append("")
    out += ["## Analysis and environment files", "", row(["File", "Contents"]), row(["---"] * 2)]
    out += [row([f"`{e['file']}`", e["description"]]) for e in entries if e["kind"] == "support"]
    return "\n".join(out) + "\n"


def build(results: Path) -> list[dict]:
    return [describe(p) for p in sorted(results.glob("*.json")) if p.name != "index.json"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("results", type=Path)
    args = parser.parse_args()
    entries = build(args.results)
    (args.results / "index.json").write_text(json.dumps(entries, indent=2) + "\n", encoding="utf-8")
    (args.results / "INDEX.md").write_text(to_markdown(entries), encoding="utf-8")
    print(f"indexed {len(entries)} files")


if __name__ == "__main__":
    main()
